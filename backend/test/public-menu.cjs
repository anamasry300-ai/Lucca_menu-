    record('خيار المزامنة يُخزَّن (توافق مع العملاء القدماء)', res.status === 200 && res.j.syncPriceWithPos === true, `sync=${res.j && res.j.syncPriceWithPos}`);
    res = await api('POST', '/api/public/admin/import', undefined, admin);
    record('إعادة استيراد بعد ضبط المزامنة لا يكتب أسعاراً', res.status === 200 && res.j.importedItems === 0, `status=${res.status} ` + JSON.stringify(res.j).slice(0, 200));
    r = await fetch(BASE + '/api/public/menu');
    j = await r.json();
    const catCheck = j.categories.find((c) => c.id === catId);
