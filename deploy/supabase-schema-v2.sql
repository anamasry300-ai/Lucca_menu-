-- =====================================================================
-- LUCCA CAFFE POS — Supabase PostgreSQL Schema v2 (Phase 1)
-- =====================================================================
-- الهدف: سكيمة كاملة تطابق مخطط SQLite (db.ts + migrations + أدوات العميل)
-- مع سياسات RLS مصمّمة حسب الدور (cashier / manager / admin) منذ البداية.
--
-- مَن يستخدم ماذا:
--   • الخادم (backend)  → service_role key  → يتجاوز RLS تماماً (المصدر الرئيسي).
--   • العميل (أونلاين)  → anon key          → يخضع لـ RLS (قراءة عامة للقائمة فقط).
--   • مستخدمو Supabase Auth → أي دور مخوَّل وفق app_user_roles.
--
-- ملاحظات تحويل الأنواع من SQLite:
--   REAL        → DOUBLE PRECISION  (SQLite REAL عائم 64bit — لا نفقد دقة الأسعار)
--   TEXT dates  → TEXT  (تُخزَّن كما هي 'YYYY-MM-DD' .. لا أخطاء توقيت/منطقة)
--   datetime('now') → NOW()  (TIMESTAMPTZ)
--   INTEGER PK AUTOINCREMENT → BIGSERIAL  |  أسماء الأعمدة camelCase تُحاط بعلامتي اقتباس
--
-- التشغيل: Supabase Dashboard > SQL Editor > لصق وتشغيل.
-- بعدها: أنشئ مستخدمي Auth تجريبيين عبر deploy/supabase-rls-seed.sql
--        ثم تحقق من RLS عبر tools/test-supabase-rls.cjs
-- =====================================================================

CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- =====================================================================
-- أدوات RLS حسب الدور
-- =====================================================================
-- خريطة مستخدم Supabase Auth → دوره في النظام. لا يوجد صف = لا وصول.
CREATE TABLE IF NOT EXISTS app_user_roles (
  user_id   UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  role      TEXT NOT NULL CHECK (role IN ('admin','manager','cashier','kitchen','device')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

DROP FUNCTION IF EXISTS public.current_app_role CASCADE;
CREATE OR REPLACE FUNCTION public.current_app_role()
RETURNS TEXT
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
  SELECT role FROM public.app_user_roles WHERE user_id = auth.uid() LIMIT 1;
$$;

DROP FUNCTION IF EXISTS public.role_in CASCADE;
CREATE OR REPLACE FUNCTION public.role_in(allowed TEXT[])
RETURNS BOOLEAN
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
  SELECT current_app_role() = ANY(allowed);
$$;

DROP FUNCTION IF EXISTS public.is_staff CASCADE;
CREATE OR REPLACE FUNCTION public.is_staff()
RETURNS BOOLEAN
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
  SELECT role_in(ARRAY['cashier','manager','admin']);
$$;

DROP FUNCTION IF EXISTS public.is_manager CASCADE;
CREATE OR REPLACE FUNCTION public.is_manager()
RETURNS BOOLEAN
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
  SELECT role_in(ARRAY['manager','admin']);
$$;

DROP FUNCTION IF EXISTS public.is_admin CASCADE;
CREATE OR REPLACE FUNCTION public.is_admin()
RETURNS BOOLEAN
LANGUAGE sql STABLE SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
  SELECT role_in(ARRAY['admin']);
$$;

