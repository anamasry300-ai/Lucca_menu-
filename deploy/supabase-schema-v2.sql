    EXECUTE format('CREATE POLICY "manager_insert_%s" ON %I FOR INSERT TO authenticated WITH CHECK (is_manager());', t, t);
    EXECUTE format('CREATE POLICY "manager_update_%s" ON %I FOR UPDATE TO authenticated USING (is_manager()) WITH CHECK (is_manager());', t, t);
    EXECUTE format('CREATE POLICY "manager_delete_%s" ON %I FOR DELETE TO authenticated USING (is_manager());', t, t);
  END LOOP;
END $$;

